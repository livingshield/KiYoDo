const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const versionJsonPath = path.join(rootDir, 'version.json');
const publicVersionJsonPath = path.join(rootDir, 'public', 'version.json');
const srcVersionTsPath = path.join(rootDir, 'src', 'version.ts');
const packageJsonPath = path.join(rootDir, 'package.json');

// Read existing version.json
let current = {
  version: '1.0.0',
  buildNumber: 0,
  buildTime: new Date().toISOString()
};

if (fs.existsSync(versionJsonPath)) {
  try {
    current = JSON.parse(fs.readFileSync(versionJsonPath, 'utf8'));
  } catch (e) {
    console.warn('Failed to parse version.json, resetting to default:', e.message);
  }
}

// Increment patch version: 1.0.1 -> 1.0.2
const versionParts = (current.version || '1.0.0').split('.').map(n => parseInt(n, 10) || 0);
while (versionParts.length < 3) versionParts.push(0);
versionParts[2] += 1;

const newVersion = versionParts.join('.');
const newBuildNumber = (current.buildNumber || 0) + 1;
const newBuildTime = new Date().toISOString();

const newVersionData = {
  version: newVersion,
  buildNumber: newBuildNumber,
  buildTime: newBuildTime
};

// 1. Write version.json
fs.writeFileSync(versionJsonPath, JSON.stringify(newVersionData, null, 2) + '\n', 'utf8');

// 2. Write public/version.json
if (!fs.existsSync(path.dirname(publicVersionJsonPath))) {
  fs.mkdirSync(path.dirname(publicVersionJsonPath), { recursive: true });
}
fs.writeFileSync(publicVersionJsonPath, JSON.stringify(newVersionData, null, 2) + '\n', 'utf8');

// 3. Write src/version.ts
const tsContent = `// This file is automatically generated and updated upon deployment
export const APP_VERSION = '${newVersion}';
export const APP_BUILD_NUMBER = ${newBuildNumber};
export const APP_BUILD_TIME = '${newBuildTime}';
`;
fs.writeFileSync(srcVersionTsPath, tsContent, 'utf8');

// 4. Update package.json
if (fs.existsSync(packageJsonPath)) {
  try {
    const pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    pkg.version = newVersion;
    fs.writeFileSync(packageJsonPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');
  } catch (e) {
    console.warn('Failed to update package.json:', e.message);
  }
}

console.log(`[Version Bump] Successfully updated app version to v${newVersion} (Build #${newBuildNumber})`);
